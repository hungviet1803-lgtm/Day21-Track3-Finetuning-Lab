#!/usr/bin/env python3
"""Follow-up to NB5: does 1-5% replay data fix the forgetting, at what target cost?

Run AFTER NB5. It does not touch the graded `correct` run or `verdict.json` — those were
pre-registered and stay as they are. This adds ONE contrast, `correct_replay`, that
differs from `correct` in exactly one variable: the training set also contains a small
slice of general-instruction data (deck §6.3, "add 1-5% replay data").

Design decisions, each one there to keep the comparison honest:

* **Questions are disjoint from `eval_regression.jsonl`.** `data/replay_questions.jsonl`
  asks about different facts; the script asserts no question or keyword overlap. Replay
  is meant to preserve the *behaviour* "answer a general question in prose", not to
  teach the 15 graded answers.
* **Answers are self-generated by the base model** (greedy, thinking off), before any
  adapter exists. Replay with the model's own outputs keeps its distribution instead of
  pulling it toward whatever style a human-written answer has. Saved to
  `data/replay_selfgen.jsonl` so the exact training data is on the record.
* **Same step budget, same LoRA spec, same mask, same seed as `correct`.** The step
  count is read back from `correct`'s row in `runs.csv` and forced, so the extra 12 rows
  cannot buy extra optimizer steps.
* **Scored exactly like NB5** — same prompt (NAIVE_PROMPT), same scorers, same frozen
  baseline (b), same regression gate.

    python scripts/replay_experiment.py
Writes `adapters/correct_replay/`, a `correct_replay` row in `results/runs.csv`, and
`results/replay_experiment.json`.
"""
from __future__ import annotations

import json
import os
import pathlib
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from labkit import data, evaluate as ev, generate, modeling, report, train   # noqa: E402
from labkit.config import SPECS, get_tier                                     # noqa: E402

KEY = "correct_replay"


def load_jsonl(p: pathlib.Path) -> list[dict]:
    return [json.loads(l) for l in p.open(encoding="utf-8") if l.strip()]


def decontaminate(questions: list[dict], regression: list[dict]) -> None:
    graded_q = {ev.normalize(r["instruction"]) for r in regression}
    keywords = {ev.normalize(k) for r in regression for k in r["keywords"]}
    for q in questions:
        nq = ev.normalize(q["instruction"])
        assert nq not in graded_q, f"replay question is a graded regression item: {q}"
        hit = [k for k in keywords if k in nq]
        assert not hit, f"replay question contains graded keyword(s) {hit}: {q}"


def self_generate(model, tok, questions: list[dict], path: pathlib.Path) -> list[dict]:
    if path.exists():
        print(f"reusing {path.relative_to(ROOT)}")
        return load_jsonl(path)
    answers, _ = generate.generate_batch(model, tok, [q["instruction"] for q in questions],
                                         system=None, max_new_tokens=192, label="replay/selfgen")
    rows = [{"instruction": q["instruction"], "output": a} for q, a in zip(questions, answers)]
    with path.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    return rows


def main() -> int:
    tier = get_tier()
    spec = SPECS["correct"]
    regression = load_jsonl(ROOT / "data" / "eval_regression.jsonl")
    target = load_jsonl(ROOT / "data" / "eval_target.jsonl")
    if int(os.environ.get("EVAL_LIMIT", "0") or 0):
        raise SystemExit("run this on the full eval sets (unset EVAL_LIMIT)")

    frozen = json.loads((ROOT / "results" / "baselines_frozen.json").read_text(encoding="utf-8"))
    base_b = ev.GroupScores(**{k: v for k, v in frozen["baseline_b"].items() if k != "extra"})
    runs = {r["run"]: r for r in report.read_rows("runs.csv", results_dir=ROOT / "results")}
    if "correct" not in runs:
        raise SystemExit("run NB3 first — need the `correct` row to match its step budget")
    correct_steps = int(runs["correct"]["max_steps"])

    questions = load_jsonl(ROOT / "data" / "replay_questions.jsonl")
    decontaminate(questions, regression)

    model, tok = generate.load_base(tier)
    replay = self_generate(model, tok, questions, ROOT / "data" / "replay_selfgen.jsonl")
    for r in replay:
        print(f"  Q: {r['instruction']}\n  A: {r['output'][:120]!r}")

    train_rows = load_jsonl(ROOT / "data" / "split" / "train.jsonl")
    mask_mode = os.environ.get("MASK_MODE", "assistant-only")
    # Records without `input` render as a bare user turn (no system message) -- the same
    # shape NB2/NB5 use for the regression probe. The triage rows keep NAIVE_PROMPT.
    rows = data.to_training_dataset(tok, train_rows + replay, max_length=tier.max_length,
                                    mask_mode=mask_mode)
    frac = len(replay) / len(rows)
    print(f"train rows: {len(rows)} ({len(replay)} replay = {frac:.1%})")

    from datasets import Dataset
    from peft import LoraConfig
    from trl import SFTConfig, SFTTrainer

    targets = modeling.resolve_target_modules(model, spec.target)
    trainable = modeling.count_lora_params(model, targets, spec.r)
    planned = train.planned_steps(len(rows), tier, float(os.environ.get("EPOCHS", "2") or 2))
    if planned != correct_steps:
        print(f"note: {len(rows)} rows would plan {planned} steps; forcing {correct_steps} "
              "to match `correct`")
    out_dir = ROOT / "adapters" / KEY
    want = train.sft_config_kwargs(tier, spec, str(out_dir), max_steps=correct_steps,
                                   mask_mode=mask_mode)
    sft_kwargs, _ = train.filter_kwargs(SFTConfig, want, label="SFTConfig[replay]")
    lora_kwargs, _ = train.filter_kwargs(LoraConfig, train.lora_config_kwargs(spec, targets),
                                         label="LoraConfig[replay]")
    generate.free_memory()
    trainer = SFTTrainer(model=model, args=SFTConfig(**sft_kwargs),
                         train_dataset=Dataset.from_list(rows), processing_class=tok,
                         peft_config=LoraConfig(**lora_kwargs))
    print("precision fix:", train.align_trainable_precision(trainer.model))
    t0 = time.perf_counter()
    res = trainer.train()
    elapsed = time.perf_counter() - t0
    trainer.model.save_pretrained(out_dir)

    row = train.summarize_run(spec, tier, targets, trainable, elapsed, generate.peak_vram_gb())
    row.update(run=KEY, label=spec.label + " · +replay", final_loss=round(res.training_loss, 4),
               mask_mode=mask_mode, max_steps=correct_steps,
               teaches=f"correct + {len(replay)} self-generated replay rows ({frac:.1%}), deck §6.3")
    report.append_row(row, results_dir=ROOT / "results")
    del trainer, model
    generate.free_memory()

    # ---- score exactly like NB5 ----
    from peft import PeftModel
    model, tok = generate.load_base(tier)
    model = PeftModel.from_pretrained(model, str(out_dir))
    model.eval()
    preds, lat = generate.generate_batch(model, tok, [r["input"] for r in target],
                                         system=generate.NAIVE_PROMPT, label=f"{KEY}/target")
    tgt = sum(ev.triage_field_accuracy(p, r["label"]) for p, r in zip(preds, target)) / len(target)
    fmt = sum(ev.has_required_keys(p, ev.TRIAGE_KEYS) for p in preds) / len(preds)
    rpreds, _ = generate.generate_batch(model, tok, [r["instruction"] for r in regression],
                                        system=None, max_new_tokens=96, label=f"{KEY}/regression")
    reg = sum(ev.keyword_recall(p, r["keywords"]) for p, r in zip(rpreds, regression)) / len(regression)
    scores = ev.GroupScores(target=tgt, regression=reg, format=fmt, latency_ms=lat, n=len(target))
    verdict = ev.regression_gate(scores, base_b)

    out = {
        "run": KEY, "n_replay": len(replay), "replay_fraction": round(frac, 4),
        "max_steps": correct_steps, "final_loss": row["final_loss"],
        "scores": scores.as_dict(), "verdict": verdict.as_dict(),
        "regression_outputs": [{"q": r["instruction"], "keywords": r["keywords"],
                                "pred": p, "recall": ev.keyword_recall(p, r["keywords"])}
                               for r, p in zip(regression, rpreds)],
        "target_errors": [{"ticket": r["input"], "label": r["label"], "pred": p}
                          for r, p in zip(target, preds)
                          if ev.triage_field_accuracy(p, r["label"]) < 1.0],
    }
    report.write_json(out, "replay_experiment.json", results_dir=ROOT / "results")
    print(json.dumps({k: out[k] for k in ("scores", "verdict")}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
